//! PrintNum — библиотека PrintNum.
//!
//! Здесь живут модули, доступные для интеграционных тестов и для бинарника
//! (`main.rs`). Публичной является чистая бизнес-логика (`config`, `print`),
//! а также HTTP-сервер.
//!
//! # Поддержка платформ
//!
//! - **Windows 7 SP1 x64 и выше** — целевая (поддерживаемая) платформа.
//!   Здесь работают печать (Win32 GDI), список/статус принтеров (Win32 Spooler)
//!   и очистка очереди.
//! - **macOS / Linux** — **только для разработки**. Проект собирается,
//!   запускается GUI и HTTP-сервер, работают тесты бизнес-логики, но функции
//!   принтера (`printer`, `print`) заменены заглушками: печать недоступна.
//!   Это сделано, чтобы вести разработку не только на Windows.
//!   Поддержка macOS/Linux как пользовательской платформы **не заявлена**.

pub mod barcode;
pub mod config;
pub mod print;
pub mod printer;
pub mod server;
pub mod settings;