/**
 * Формат штрихкода отправления Ozon: 'ii' + 9–14 цифр.
 * Примеры: ii18725308927, ii8923223139, ii323324234.
 *
 * Нужен, чтобы не подставлять в генератор ШК номер отправления
 * ('0114344617-0034-1') или название товара — они копируются теми
 * же кнопками.
 */
export const LABEL_BARCODE_RE = /^ii\d{9,14}$/;

/**
 * Формат ячейки, которую можно печатать: только цифры и дефисы.
 *
 * Примеры: '1-1', '5-3', '163-1'. Полка кодируется ведущим дефисом
 * ('-88') и проверяется отдельно (`SHELF_CODE_RE`).
 *
 * Текстовые ячейки ('Возврат-1', 'Прямой поток-5') не проходят: служба
 * принимает только цифры/дефис/пробел и отклоняет кириллицу.
 */
export const CELL_PRINTABLE_RE = /^[\d\-]+$/;

